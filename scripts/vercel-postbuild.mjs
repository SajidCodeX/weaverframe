/**
 * vercel-postbuild.mjs
 *
 * Converts vite build output (dist/server/ + dist/client/) into
 * Vercel Build Output API v3 format (.vercel/output/).
 *
 * This runs AFTER `vite build --config vite.config.vercel.ts` and only if
 * the Nitro vercel preset hasn't already created .vercel/output/ itself.
 *
 * src/server.ts exports a Web-standard fetch(request, env, ctx) handler,
 * which Vercel's Node.js runtime v18+ supports natively via Response return.
 */

import { cpSync, existsSync, mkdirSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = process.cwd();
const VERCEL_OUT = join(ROOT, ".vercel", "output");
const DIST_CLIENT = join(ROOT, "dist", "client");
const DIST_SERVER = join(ROOT, "dist", "server");

// --- Guard: if Nitro already created .vercel/output, nothing to do ---
if (existsSync(join(VERCEL_OUT, "config.json"))) {
  console.log(
    "✅ .vercel/output already exists (generated by Nitro vercel preset). Skipping manual conversion."
  );
  process.exit(0);
}

console.log(
  "⚙️  Nitro preset not detected — manually converting build output to Vercel Build Output API format..."
);

if (!existsSync(DIST_CLIENT)) {
  console.error("❌ dist/client not found. Run vite build first.");
  process.exit(1);
}
if (!existsSync(DIST_SERVER)) {
  console.error("❌ dist/server not found. Run vite build first.");
  process.exit(1);
}

// 1. Create directory structure
const STATIC_DIR = join(VERCEL_OUT, "static");
const FUNC_DIR = join(VERCEL_OUT, "functions", "server.func");
mkdirSync(STATIC_DIR, { recursive: true });
mkdirSync(FUNC_DIR, { recursive: true });

// 2. Copy static client assets → .vercel/output/static/
console.log("📁 Copying client assets to .vercel/output/static/ ...");
cpSync(DIST_CLIENT, STATIC_DIR, { recursive: true });

// 3. Copy server bundle → .vercel/output/functions/server.func/
console.log("📁 Copying server bundle to .vercel/output/functions/server.func/ ...");
cpSync(DIST_SERVER, FUNC_DIR, { recursive: true });

// 4. Write .vc-config.json (Vercel function config)
//    supportsResponseStreaming: true  → lets us return a Web Response directly
writeFileSync(
  join(FUNC_DIR, ".vc-config.json"),
  JSON.stringify(
    {
      runtime: "nodejs22.x",
      handler: "index.js",
      supportsResponseStreaming: true,
    },
    null,
    2
  )
);

// 5. Write thin index.js wrapper
//    server.js exports { default: { fetch(request, env, ctx) } }
//    Vercel Node.js runtime calls the default export with (request) and expects a Response.
writeFileSync(
  join(FUNC_DIR, "index.js"),
  `// Auto-generated by scripts/vercel-postbuild.mjs
// Wraps the TanStack Start SSR fetch handler for Vercel's Node.js serverless runtime.
import app from "./server.js";

export default async function handler(request) {
  return app.fetch(request, {}, {});
}
`
);

// 6. Write config.json (Vercel routing rules)
writeFileSync(
  join(VERCEL_OUT, "config.json"),
  JSON.stringify(
    {
      version: 3,
      routes: [
        // Cache static assets indefinitely (content-hashed filenames)
        {
          src: "^/_build/assets/(.*)$",
          headers: { "cache-control": "public, max-age=31536000, immutable" },
          continue: true,
        },
        // Serve static files from CDN if they exist
        { handle: "filesystem" },
        // All other requests → SSR function
        { src: "/(.*)", dest: "/server" },
      ],
    },
    null,
    2
  )
);

console.log("✅ .vercel/output/ created successfully!");
console.log("   → static/      (client assets)");
console.log("   → functions/server.func/  (SSR handler)");
console.log("   → config.json  (routing rules)");
